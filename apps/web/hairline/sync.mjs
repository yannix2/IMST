// Turns the Hairline figures in this folder (bench format, checked with the
// hairline-create skill's look.mjs) into ES modules the site can import.
//
//   node hairline/sync.mjs [path/to/hairline-create/kernel.js]
//
// kernel.js is @lucasmarkes/hairline's core (MIT), unchanged; the package does not
// export it, so a vendored copy sits beside the generated figures.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "components", "hairline", "generated");
const kernelPath = process.argv[2] ?? join(homedir(), ".claude", "skills", "hairline-create", "kernel.js");

mkdirSync(out, { recursive: true });
const banner = "// GENERATED by hairline/sync.mjs. Edit the source in apps/web/hairline/, then re-run.\n";

writeFileSync(join(out, "kernel.js"), `${banner}// @lucasmarkes/hairline core, MIT licence.\n${readFileSync(kernelPath, "utf8")}\nexport { HL };\n`);

for (const file of readdirSync(here).filter((f) => f.endsWith(".js"))) {
  const source = readFileSync(join(here, file), "utf8");
  if (!source.includes("hairline({")) throw new Error(`${file}: no hairline({ ... }) registration found`);
  const module = source.replace(/\nhairline\(\{/, "\nexport const figure = ({");
  writeFileSync(join(out, file), `${banner}import { HL } from "./kernel.js";\n${module}`);
  console.log(`synced ${file}`);
}
