// Still frames of the Hairline figures as static icons (wave 2: "Hairline as icons"). Opens each
// bench page (hairline-*.html) in the workspace's Playwright Chromium under reduced motion,
// takes the figure's SVG at rest, crops it to the drawing and writes
// src/components/hairline/icons-data.ts. No engine and no JavaScript ship with an icon.
//
//   node hairline/icons.mjs
import { createRequire } from "node:module";
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "components", "hairline", "icons-data.ts");
const pnpm = join(here, "..", "..", "..", "node_modules", ".pnpm");
const pw = readdirSync(pnpm).find((d) => /^playwright@\d/.test(d));
const require = createRequire(join(pnpm, pw, "node_modules", "playwright", "package.json"));
const { chromium } = require("playwright");
const msp = join(process.env.LOCALAPPDATA ?? "", "ms-playwright");
const chromiumDir = readdirSync(msp).filter((d) => d.startsWith("chromium-")).sort().pop();

const browser = await chromium.launch({ executablePath: join(msp, chromiumDir, "chrome-win64", "chrome.exe") });
const page = await browser.newPage({ viewport: { width: 900, height: 900 }, reducedMotion: "reduce" });
const icons = {};
for (const f of readdirSync(here).filter((f) => /^hairline-.*\.html$/.test(f)).sort()) {
  const name = f.replace(/^hairline-|\.html$/g, "");
  await page.goto(pathToFileURL(join(here, f)).href);
  await page.waitForTimeout(1500);
  icons[name] = await page.evaluate(() => {
    const svg = [...document.querySelectorAll("svg")].sort((a, b) => b.querySelectorAll("*").length - a.querySelectorAll("*").length)[0];
    const box = svg.getBBox();
    const pad = 6;
    // Keep only the drawing: shapes with their d / geometry and class; drop empty groups.
    const clone = svg.cloneNode(true);
    clone.querySelectorAll("g").forEach((g) => !g.children.length && g.remove());
    clone.querySelectorAll("*").forEach((n) => {
      for (const a of [...n.attributes]) if (!["d", "class", "cx", "cy", "r", "points", "x1", "y1", "x2", "y2"].includes(a.name)) n.removeAttribute(a.name);
    });
    return {
      viewBox: [box.x - pad, box.y - pad, box.width + pad * 2, box.height + pad * 2].map((v) => Math.round(v * 10) / 10).join(" "),
      body: clone.innerHTML.replace(/\s+/g, " ").trim(),
    };
  });
  console.log(`${name}: ${icons[name].viewBox}, ${icons[name].body.length} chars`);
}
await browser.close();

const ts = `// GENERATED by hairline/icons.mjs from the Hairline bench pages. Do not edit by hand.
// Each entry is a figure's still frame: the cropped viewBox and the SVG markup inside it.
export const hairlineIcons = ${JSON.stringify(icons, null, 2)} as const;
export type HairlineIconName = keyof typeof hairlineIcons;
`;
writeFileSync(out, ts);
console.log(`wrote ${out}`);
