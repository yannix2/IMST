// Turns the approved selection (media-selection.json) into the files the site serves (wave 2,
// task 1.3): AVIF + WebP at 480 / 960 / 1600 px wide (never upscaled), metadata stripped (sharp
// drops EXIF and GPS unless asked to keep them), a tiny blurred placeholder, and the typed manifest
// apps/web/src/content/media.ts. Originals stay in IMSTMEDIA.
//
//   node build-media.mjs [--root E:\IMST\IMSTMEDIA]

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { mediaRoot, upright } from "./source.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, "..", "..", "apps", "web");
const outDir = join(app, "public", "media", "photos");
const manifest = join(app, "src", "content", "media.ts");
const root = mediaRoot();

const widths = [480, 960, 1600];
const selection = JSON.parse(readFileSync(join(here, "media-selection.json"), "utf8"));
mkdirSync(outDir, { recursive: true });

const entries = [];
let bytes = 0;
for (const photo of selection.photos) {
  const { buffer, width, height, date } = await upright(photo, root);
  // Never upscale: a photo narrower than 1600 px gets its own width as the largest size.
  const sizes = widths.filter((w) => w <= width);
  if (width < widths.at(-1) && !sizes.includes(width)) sizes.push(width);
  const files = [];
  for (const w of sizes) {
    const base = join(outDir, `${photo.id}-${w}`);
    const resized = sharp(buffer).resize({ width: w });
    const avif = await resized.clone().avif({ quality: 50, effort: 5 }).toFile(`${base}.avif`);
    const webp = await resized.clone().webp({ quality: 72, effort: 5 }).toFile(`${base}.webp`);
    bytes += avif.size + webp.size;
    files.push(w);
  }
  const blur = await sharp(buffer).resize({ width: 16 }).blur(1).webp({ quality: 40 }).toBuffer();
  entries.push({
    id: photo.id,
    event: photo.event,
    date,
    consent: photo.consent,
    width,
    height,
    widths: files,
    focus: photo.focus ?? [0.5, 0.5],
    blur: `data:image/webp;base64,${blur.toString("base64")}`,
    alt: photo.alt,
  });
  console.log(`${photo.id.padEnd(24)} ${width}x${height}  ${date ?? "no date"}  [${files.join(", ")}]`);
}

const ts = `// GENERATED by tools/media/build-media.mjs from tools/media/media-selection.json. Do not edit by
// hand: change the selection and run \`node build-media.mjs\` in tools/media. Photos are the school's
// own (IMSTMEDIA, 2025-26 and 2026-27); consent per owner decision 2026-11-06: students only in
// non-identifiable shots, adults may be recognisable. Files: /media/photos/<id>-<width>.(avif|webp).
import type { Photo } from "@maarif/contracts/media";

export type { Photo };

export const photos = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.id, e])), null, 2)} satisfies Record<string, Photo>;

export type PhotoId = keyof typeof photos;
export const heroPhotos = ${JSON.stringify(selection.hero)} as const satisfies readonly PhotoId[];
`;
mkdirSync(dirname(manifest), { recursive: true });
writeFileSync(manifest, ts);
console.log(`\n${entries.length} photos, ${(bytes / 1e6).toFixed(1)} MB written to ${outDir}`);
if (!existsSync(manifest)) process.exit(1);
